import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Renderers need dimensions and existence, not a copy of every public image in
// each function bundle. Rebuild before dev/build so new content is included.
const root=path.resolve('public');
const assets={};
for(const rel of (await fs.readdir(root,{recursive:true})).sort()){
  if(!/\.(png|jpe?g|webp|avif|gif|svg|ico)$/i.test(rel))continue;
  const abs=path.join(root,rel);
  if(!(await fs.stat(abs)).isFile())continue;
  const key='/'+rel.replaceAll('\\','/');
  assets[key]=null;
  try{const m=await sharp(abs).metadata();if(m.width&&m.height)assets[key]={width:m.width,height:m.height};}catch{}
}
await fs.writeFile('src/data/public-assets.ts','// Generated by scripts/build-public-assets.mjs. Do not edit by hand.\nexport const publicAssets: Record<string, {width:number;height:number}|null> = '+JSON.stringify(assets,null,2)+';\n');
console.log(`Indexed ${Object.keys(assets).length} public images without bundling their bytes.`);
