"""Generate local unicode-range shards without dropping any original characters.

Run manually with Python + fonttools[woff]; generated assets are committed, so
production builds need neither Python nor a font download. The existing
Pretendard ranges group commonly used Korean syllables together. Any Noto-only
characters are retained in additional shards. Bump OUTPUT_VERSION on changes.
"""
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
import re
import subprocess
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_VERSION = "noto-serif-kr-v1"
OUT = ROOT / "public/fonts" / OUTPUT_VERSION
FONTS = [("Regular", 400), ("SemiBold", 600), ("Bold", 700)]


def codepoints(value):
    result = set()
    for token in value.split(","):
        ends = token.strip().upper().removeprefix("U+").split("-")
        result.update(range(int(ends[0], 16), int(ends[-1], 16) + 1))
    return result


def unicode_range(points):
    ranges = []
    start = end = sorted(points)[0]
    for point in sorted(points)[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append(f"U+{start:X}" + (f"-{end:X}" if start != end else ""))
            start = end = point
    ranges.append(f"U+{start:X}" + (f"-{end:X}" if start != end else ""))
    return ",".join(ranges)


def generate(font_spec):
    name, weight = font_spec
    # Native WOFF2 decoding avoids repeatedly reconstructing 11,000+ glyphs in Python.
    decoded = ROOT / f"tmp/font-subsets/{name}.ttf"
    original = TTFont(decoded)
    remaining = set(original.getBestCmap())
    source_ranges = re.findall(r"unicode-range:\s*([^;]+);", (ROOT / "src/app/pretendard.css").read_text(encoding="utf-8"))
    groups = []
    for value in source_ranges:
        points = codepoints(value) & remaining
        if points:
            groups.append(points)
            remaining -= points
    extra = sorted(remaining)
    groups.extend(set(extra[i:i + 256]) for i in range(0, len(extra), 256))
    covered = set()
    css = []
    for index, points in enumerate(groups):
        filename = f"{name}.{index}.woff2"
        if "--resume" not in sys.argv or not (OUT / filename).exists():
            font = TTFont(decoded)
            font.flavor = "woff2"
            options = subset.Options()
            options.name_IDs = ["*"]  # Keep copyright and licensing metadata.
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points)
            worker.subset(font)
            font.save(OUT / filename)
        with TTFont(OUT / filename) as saved:
            # Shared glyphs can keep additional cmap aliases; unicode-range still
            # restricts the face to this shard's disjoint set of characters.
            assert points <= set(saved.getBestCmap()), f"Coverage mismatch: {filename}"
        assert not (covered & points), "Overlapping unicode ranges"
        covered |= points
        css.append(f"@font-face {{\n  font-family: 'Noto Serif KR';\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n  src: url('/fonts/{OUTPUT_VERSION}/{filename}') format('woff2');\n  unicode-range: {unicode_range(points)};\n}}")
    assert covered == set(original.getBestCmap()), "Missing original characters"
    print(f"{name}: {len(groups)} shards, {len(covered)} characters verified", flush=True)
    return "\n\n".join(css)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    subprocess.run(["node", "scripts/decompress-serif-fonts.mjs"], cwd=ROOT, check=True)
    with ProcessPoolExecutor(max_workers=3) as pool:
        sheets = list(pool.map(generate, FONTS))
    (ROOT / "src/app/noto-serif.css").write_text(
        "/* Generated by scripts/subset-serif-fonts.py. Noto Serif KR: SIL OFL 1.1. */\n" + "\n\n".join(sheets) + "\n", encoding="utf-8")
